import { execFileSync } from 'node:child_process';
import { writeFileSync, unlinkSync } from 'node:fs';
import { repoRoot } from './config.mjs';

function git(args) {
  return execFileSync('git', args, { cwd: repoRoot(), encoding: 'utf8' }).trim();
}

function gh(args) {
  return execFileSync('gh', args, { cwd: repoRoot(), encoding: 'utf8' }).trim();
}

/**
 * Creates a branch, commits exactly one content file, pushes, and opens a
 * **draft** PR. Never merges, never approves. Returns the PR URL.
 *
 * This function refuses to run against `main`/`master` directly — it always
 * creates a dedicated branch first, so a bug here can't push straight to
 * the default branch.
 */
export function openEditorialDraftPr({ filePath, decision, evidencePacket, draftContent, runId }) {
  const currentBranch = git(['rev-parse', '--abbrev-ref', 'HEAD']);
  if (currentBranch === 'main' || currentBranch === 'master') {
    throw new Error(`Refusing to commit editorial content on ${currentBranch} — must be on a dedicated branch.`);
  }

  const branch = `editorial/${draftContent.slug}-${new Date().toISOString().slice(0, 10)}`;
  git(['checkout', '-b', branch]);
  git(['add', '--', filePath]);

  const staged = git(['diff', '--cached', '--name-only']).split('\n').filter(Boolean);
  if (staged.length !== 1 || staged[0] !== relativePath(filePath)) {
    throw new Error(
      `Refusing to commit: expected exactly one staged file (${relativePath(filePath)}), got: ${JSON.stringify(staged)}`,
    );
  }

  const commitMessage = `Add draft article: ${draftContent.title}\n\nrunId: ${runId}\nscore: ${decision.score}\noutcome: ${decision.outcome}\n\nGenerated by the daily editorial automation. Requires human review before merge — see docs/DAILY-AUTOMATION.md.`;
  git(['commit', '-m', commitMessage]);
  git(['push', '-u', 'origin', branch]);

  const bodyPath = `${repoRoot()}artifacts/pr-body.md`;
  writeFileSync(bodyPath, buildPrBody({ decision, evidencePacket, draftContent, runId }));

  const url = gh([
    'pr',
    'create',
    '--draft',
    '--base',
    'main',
    '--head',
    branch,
    '--title',
    `[editorial-draft] ${draftContent.title}`,
    '--body-file',
    bodyPath,
    '--label',
    'ai-generated-content',
  ]);
  unlinkSync(bodyPath);

  return { url: url.trim(), branch };
}

function relativePath(p) {
  const root = repoRoot();
  return p.startsWith(root) ? p.slice(root.length) : p;
}

function buildPrBody({ decision, evidencePacket, draftContent, runId }) {
  const sourcesList = draftContent.sources
    .map((s) => `- [${s.title}](${s.url}) — ${s.publisher} (${s.tier}, accessed ${s.accessDate})`)
    .join('\n');

  return `## AI-generated editorial draft — human review required

This article was produced by the daily editorial automation and is **not
approved for publication**. It must be reviewed and merged by a human
editor, never auto-merged.

- **Run ID:** \`${runId}\`
- **Pillar:** ${draftContent.pillar}
- **Risk class:** ${draftContent.riskClass}
- **Deterministic score:** ${decision.score}/100 (${JSON.stringify(decision.scoreBreakdown)})
- **Search signal:** ${evidencePacket.searchSignal?.topQueries?.length ?? 0} query(ies) considered

## Sources cited

${sourcesList}

## Editorial checklist before merging

- [ ] Every factual claim traces to a source above
- [ ] No implication that freeze-drying kills pathogens
- [ ] No fabricated first-party testing/reviews/testimonials
- [ ] Cottage-food-law content (if any) hedges to "confirm with your local authority"
- [ ] Voice matches the site (no banned language)
- [ ] \`npm run build\` and the link/JSON-LD checker passed in CI on this branch

Full run log, evidence packet, and verification result are attached as CI
artifacts on this branch's workflow run (90-day retention).
`;
}
