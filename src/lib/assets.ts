/**
 * The photography catalog.
 *
 * One entry per photograph we may publish, with its provenance and its limits
 * recorded next to it. Templates ask for an asset by intent — "a 16:9 camping
 * photograph" — and never by path, so a slot cannot be filled by whatever
 * happened to be lying in `public/images/` when someone went looking.
 *
 * Three things this file exists to prevent, each of which has already happened
 * once on this project or was one merge away:
 *
 *  1. A photograph of the wrong machine. A file named `using_the_freeze_dryer`
 *     turned out to be a steam autoclave — opposite machine, opposite physics.
 *     Every `equipment` entry here was confirmed by looking at the frame for a
 *     vacuum chamber, a sealed door, stacked flat trays and a separate pump.
 *  2. A stock photograph of a commercial pouch standing in for our packaging.
 *     `not-product-imagery` is not advice; `tests/assets.test.mjs` fails the
 *     build if one reaches a product surface. A removed label does not make a
 *     pouch ours.
 *  3. Alt text that describes a photograph nobody has. Alt lives here, with the
 *     photograph, rather than being copied into each article that uses it —
 *     which is how `/guides/which-freeze-dryer` came to promise screen-reader
 *     users "a person loading a tray" for a frame containing no person.
 *
 * Derivatives are generated by `assets/build-derivatives.mjs` and committed.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { CATALOG } from './commerce.ts';

export type AssetClass =
  | 'product'        // our catalog items
  | 'food'           // isolated food on white
  | 'equipment'      // verified freeze dryers, trays, sealing in progress
  | 'camping'        // outdoor, trail context
  | 'process'        // packing, sealing, labeling
  | 'line-hero'      // wide, atmospheric, represents a line
  | 'brand';         // portrait, workspace

export type AssetSource = 'own' | 'manufacturer' | 'stock';

export type AssetRatio = '16:9' | '4:5' | '1:1';

/**
 * The restriction vocabulary, closed on purpose.
 *
 * A free `string[]` lets a typo become a silently unenforced rule: nothing
 * matches `'not-product-imagry'`, and the asset walks into a product card.
 */
export type AssetRestriction =
  /** Stock photography of someone else's commercial packaging. May illustrate
   *  the activity; may never represent Sublime Pantry packaging or appear in a
   *  product context. */
  | 'not-product-imagery'
  /** Editorial use only — a caption is required wherever it renders. */
  | 'editorial-illustration-only'
  /** Equipment we do not own and have not tested. The site says in print that
   *  we have bench-tested no machine; alt text and captions must not imply
   *  otherwise. */
  | 'not-our-equipment'
  /** Admitted with its source unconfirmed. Labelled conservatively until a
   *  licence record turns up. Surfaced in docs/ASSET-LIBRARY.md rather than
   *  buried in a field. */
  | 'provenance-unverified'
  /** The unit visible in frame carries a legible third brand that is not one
   *  of the machines the page reviews or compares. `not-our-equipment` alone
   *  reads as "not tested by us," which a skimming reader can still misparse
   *  as "one of the compared machines, just not our unit." */
  | 'not-a-reviewed-model';

export interface Asset {
  id: string;                 // stable kebab-case, never renamed
  src: string;                // base path; derivatives resolved by helper
  alt: string;                // what is visible, not what we wish were visible
  cls: AssetClass;
  source: AssetSource;
  credit?: string;            // 'Photo: PackFreshUSA' | 'Stock photo' | 'Illustrative'
  ratios: AssetRatio[];       // which crops were generated
  /** How the ratio was reached. 'cover' centre-crops; 'contain' scales the
   *  whole frame in and pads with white, for subjects isolated on white where
   *  a crop would cut the subject. Must match `fit` in assets/sources.json —
   *  tests/assets.test.mjs fails if the two disagree, because the width ladder
   *  is computed differently for each and a mismatch means the manifest claims
   *  files that are not there (or misses files that are). */
  fit?: 'cover' | 'contain';
  intrinsic: { w: number; h: number };
  subject: string[];          // ['strawberry','fruit'] — for matching
  /** Hard constraints. Enforced by tests, not by convention. */
  restrictions?: AssetRestriction[];
  usedBy: string[];           // populated at build; where it currently appears
}

