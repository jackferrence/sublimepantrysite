/**
 * Wording a restriction obliges the caption to carry, generated rather than
 * typed.
 *
 * `/guides/which-freeze-dryer` used to spell "not a Sublime Pantry test unit"
 * into its own front matter. That works exactly until someone swaps the
 * photograph and does not copy the sentence across — and the site states in
 * print that we have bench-tested no machine, so losing it turns a true page
 * into a misleading one. Deriving it from `not-our-equipment` means the note
 * travels with the photograph and cannot be dropped by hand.
 */
const RESTRICTION_NOTE: Partial<Record<AssetRestriction, string>> = {
  'not-our-equipment': 'not a Sublime Pantry test unit',
  'not-product-imagery': 'not Sublime Pantry packaging',
  'not-a-reviewed-model': 'not one of the machines reviewed here',
};

/** The visible caption: credit first, then any note its restrictions oblige. */
export function caption(asset: Asset): string | undefined {
  const notes = (asset.restrictions ?? []).map((r) => RESTRICTION_NOTE[r]).filter(Boolean);
  const parts = [asset.credit, ...notes].filter(Boolean);
  return parts.length ? parts.join(' — ') : undefined;
}

/** `<base>/<ratio>-<width>.webp`. Mirrors `assets/build-derivatives.mjs`. */
export function derivative(asset: Asset, ratio: AssetRatio, width: number): string {
  return `${asset.src}/${ratio.replace(':', 'x')}-${width}.webp`;
}

/**
 * Widths actually emitted for a ratio — never an upscale.
 *
 * The ceiling depends on how the ratio was reached. A `cover` derivative is cut
 * out of the frame, so the ceiling is the cropped width; a `contain` one keeps
 * the whole frame and pads, so the ceiling is the intrinsic width. Getting this
 * wrong does not fail loudly: the manifest simply claims a set of files that
 * differs from what is on disk, and a `srcset` entry 404s.
 */
export function widthsFor(asset: Asset, ratio: AssetRatio): number[] {
  const { w, h } = asset.intrinsic;
  const ceiling = asset.fit === 'contain' ? w : Math.min(w, Math.round(h * RATIO_VALUE[ratio]));
  return DERIVATIVE_WIDTHS.filter((width) => width <= ceiling);
}

/** `srcset` for a ratio, widest last. Empty when the ratio was not generated. */
export function srcSet(asset: Asset, ratio: AssetRatio): string {
  if (!asset.ratios.includes(ratio)) return '';
  return widthsFor(asset, ratio)
    .map((width) => `${derivative(asset, ratio, width)} ${width}w`)
    .join(', ');
}

/** The largest generated width for a ratio — the `src` an <img> should carry. */
export function largest(asset: Asset, ratio: AssetRatio): { src: string; w: number; h: number } | null {
  if (!asset.ratios.includes(ratio)) return null;
  const widths = widthsFor(asset, ratio);
  const width = widths.at(-1);
  if (!width) return null;
  return { src: derivative(asset, ratio, width), w: width, h: Math.round(width / RATIO_VALUE[ratio]) };
}

/**
 * Where each asset currently appears, read from the two places that decide it:
 * article front matter and the commerce catalog. Computed rather than typed,
 * because a hand-maintained usage list is wrong the first time someone moves a
 * photograph and does not think to come back here.
 */
function usage(): Map<string, string[]> {
  const map = new Map<string, string[]>();
  const add = (id: string, where: string) => map.set(id, [...(map.get(id) ?? []), where]);

  const dir = join(process.cwd(), 'src/content/articles');
  if (existsSync(dir)) {
    for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
      const data = JSON.parse(readFileSync(join(dir, file), 'utf8')) as {
        image?: { assetId?: string };
      };
      if (data.image?.assetId) add(data.image.assetId, `article: ${file.replace(/\.json$/, '')}`);
    }
  }
  for (const product of CATALOG) {
    for (const image of product.images) {
      if (image.assetId) add(image.assetId, `product: ${product.sku}`);
    }
  }
  return map;
}

const USAGE = usage();

export const ASSETS: Asset[] = MANIFEST.map((a) => ({ ...a, usedBy: USAGE.get(a.id) ?? [] }));

const BY_ID = new Map(ASSETS.map((a) => [a.id, a]));

export function getAsset(id: string): Asset | null {
  return BY_ID.get(id) ?? null;
}

/**
 * The context a slot renders in. `product` is anything that represents
 * something we sell — a card, a PDP, a cart line. `editorial` is everything
 * else. The distinction is the whole point of `not-product-imagery`.
 */
export type AssetContext = 'product' | 'editorial';

export interface AssetQuery {
  cls?: AssetClass;
  /** Every listed subject must be present — narrowing, not widening. */
  subject?: string | string[];
  ratio?: AssetRatio;
  context?: AssetContext;
  /** Drop anything carrying any restriction at all. */
  excludeRestricted?: boolean;
}

/**
 * Assets matching every stated criterion, in manifest order.
 *
 * There is no fuzzy fallback and no "closest match". An empty result means the
 * slot renders nothing, which is the correct outcome: an article about machines
 * must never receive a photograph of fruit because the slot was open.
 */
export function findAssets(query: AssetQuery = {}): Asset[] {
  const subjects = query.subject
    ? Array.isArray(query.subject) ? query.subject : [query.subject]
    : [];

  return ASSETS.filter((asset) => {
    if (query.cls && asset.cls !== query.cls) return false;
    if (query.ratio && !asset.ratios.includes(query.ratio)) return false;
    if (!subjects.every((s) => asset.subject.includes(s))) return false;

    const restrictions = asset.restrictions ?? [];
    if (query.excludeRestricted && restrictions.length) return false;
    // A product context is the one the restriction was written for. Enforced
    // here as well as in tests so the wrong photograph cannot reach a card
    // even in a template nobody thought to test.
    if (query.context === 'product' && restrictions.includes('not-product-imagery')) return false;
    return true;
  });
}

/** The single best match, or null. Never an approximation. */
export function findAsset(query: AssetQuery = {}): Asset | null {
  return findAssets(query)[0] ?? null;
}
